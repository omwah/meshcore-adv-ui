# Modified for MeshMash: added the optional HEADER, TYPE, RANGES and NEXT
# arguments (generated include, struct type name, a code point filter so only
# the glyphs the UI needs are linked, and a fallback layer), and the table
# lists code points as runs of consecutive values instead of one per glyph.
# write_c() is shared with scripts/gen_unicode.py.
"""
Convert a fixed-width BDF bitmap font into a C table for the display console
(components/esp_display). Run by the build; the output is never committed, and
the font itself comes from a vendored archive (third_party/, e.g. Spleen).

    bdf2c.py FONT.bdf OUT.c [SYMBOL [NAME [PAD [MAXCOLS [HEADER [TYPE [RANGES [NEXT]]]]]]]]]
                          (HEADER: the include for TYPE, default
                           esp_display_font.h; TYPE: default esp_display_font_t;
                           RANGES: "0x20-0x7e,0xa0-0xff", default all glyphs;
                           NEXT: symbol of the fallback layer, default none)
                          (SYMBOL: default esp_display_font; NAME, as :EspFont
                           shows it: default the BDF file's name; PAD: blank
                           pixel columns added on the right of every cell;
                           MAXCOLS: at most this many columns with it, 0 any)

The table holds one glyph per code point, sorted (and indexed by runs, see
ui/gfx/font.h), each as `height` rows of
`width` bits, one byte per row for widths up to 8 and two (big-endian) up to 16,
most significant bit leftmost. Glyphs are placed in the cell by their bounding
boxes, so fonts whose glyphs don't all fill the font's box still line up on the
baseline.
"""

import sys


def parse(path):
    glyphs, font_box = {}, None
    enc = bbx = rows = None
    with open(path, encoding="latin-1") as f:
        for line in f:
            w = line.split()
            if not w:
                continue
            if w[0] == "FONTBOUNDINGBOX":
                font_box = tuple(int(x) for x in w[1:5])
            elif w[0] == "ENCODING":
                enc = int(w[1])
            elif w[0] == "BBX":
                bbx = tuple(int(x) for x in w[1:5])
            elif w[0] == "BITMAP":
                rows = []
            elif w[0] == "ENDCHAR":
                if enc is not None and enc >= 0 and bbx is not None:
                    glyphs[enc] = (bbx, rows)
                enc = bbx = rows = None
            elif rows is not None:
                rows.append(int(w[0], 16))
    return font_box, glyphs


def in_ranges(cp, ranges):
    return any(lo <= cp <= hi for lo, hi in ranges)


def parse_ranges(spec):
    out = []
    for part in spec.split(","):
        lo, _, hi = part.partition("-")
        out.append((int(lo, 0), int(hi or lo, 0)))
    return out


def runs_of(cps):
    """Sorted code points -> [(first, count, glyph index)]."""
    runs = []
    for i, cp in enumerate(cps):
        if runs and cp == runs[-1][0] + runs[-1][1]:
            runs[-1][1] += 1
        else:
            runs.append([cp, 1, i])
    return runs


def write_c(out, source, header, ctype, symbol, name, width, height, bpr, max_cols, table, nxt=""):
    """Write a font table; `table` is [(cp, [row ints])] sorted by cp."""
    runtype = ctype.replace("font", "run")
    with open(out, "w") as o:
        o.write(f"/* Generated by scripts/bdf2c.py from {source}; do not edit. */\n")
        o.write(f'#include "{header}"\n\n')
        if nxt:
            o.write(f"extern const {ctype} {nxt};\n\n")
        runs = runs_of([cp for cp, _ in table])
        o.write(f"static const {runtype} {symbol}_runs[] = {{\n")
        for i in range(0, len(runs), 6):
            o.write("    " + " ".join(f"{{0x{f:04x},{n},{x}}}," for f, n, x in runs[i:i + 6]) + "\n")
        o.write("};\n\n")
        o.write(f"const {ctype} {symbol} = {{\n"
                f"    .name = \"{name}\",\n"
                f"    .width = {width}, .height = {height}, .bytes_per_row = {bpr},\n"
                f"    .max_cols = {int(max_cols)}, .nruns = {len(runs)}, .runs = {symbol}_runs,\n")
        if nxt:
            o.write(f"    .next = &{nxt},\n")
        o.write("    .bitmaps = (const uint8_t[]){\n")
        for cp, cell in table:
            b = [x for v in cell for x in v.to_bytes(bpr, "big")]
            o.write("        " + " ".join(f"0x{x:02x}," for x in b) + f"  /* U+{cp:04X} */\n")
        o.write("    },\n};\n")


def main(src, out, symbol="esp_display_font", name=None, pad="0", max_cols="0",
         header="esp_display_font.h", ctype="esp_display_font_t", ranges="", nxt=""):
    (fw, fh, fx, fy), glyphs = parse(src)
    if ranges:
        rs = parse_ranges(ranges)
        glyphs = {cp: g for cp, g in glyphs.items() if in_ranges(cp, rs)}
    fw0, fw = fw, fw + int(pad)             # glyphs stay left-aligned; the pad is blank
    if fw > 16:
        sys.exit(f"bdf2c: {src}: glyphs wider than 16 pixels are not supported")
    bpr = 1 if fw <= 8 else 2               # bytes per row
    mask = (1 << (8 * bpr)) - 1
    if name is None:
        name = src.split("/")[-1].rsplit(".", 1)[0]
    table = []
    for cp in sorted(glyphs):
        (gw, gh, gx, gy), rows = glyphs[cp]
        nbytes = (gw + 7) // 8
        cell = [0] * fh
        top = fh - (gy - fy) - gh              # glyph's top row within the cell
        for r, bits in enumerate(rows):
            y = top + r
            if 0 <= y < fh:
                # the glyph's bits, left-aligned in a row of bpr bytes, then
                # shifted by the glyph's x offset in the cell
                v = bits << (8 * (bpr - nbytes)) if nbytes <= bpr else bits >> (8 * (nbytes - bpr))
                v = (v >> (gx - fx)) & mask if gx >= fx else (v << (fx - gx)) & mask
                # only the font's own columns: a glyph's box can spill into the pad
                v &= mask ^ ((1 << (8 * bpr - fw0)) - 1)
                cell[y] = v
        table.append((cp, cell))
    write_c(out, src.split("/")[-1], header, ctype, symbol, name, fw, fh, bpr, max_cols, table, nxt)


if __name__ == "__main__":
    main(*sys.argv[1:11])
