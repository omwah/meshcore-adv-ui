#!/usr/bin/env python3
"""
Generate the font tables in src/gen/ from the Spleen BDFs in fonts/ and, for
profiles beyond `none`, a Unicode fallback layer per size drawn from Noto Sans
Mono (scripts/gen_unicode.py). Run by the PlatformIO pre-build script
(scripts/pio_pre.py) and by `pixi run fonts`; output is never committed.

The coverage is chosen at build time (scripts/unicode_profiles.py): the
MC_UNICODE environment variable, else the environment's `custom_unicode`
option in platformio.ini (passed in by pio_pre.py), else the default profile.

  MC_UNICODE=min python -I scripts/gen_fonts.py
  python -I scripts/gen_fonts.py --report      # what each layer costs
"""

import hashlib
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bdf2c  # noqa: E402
import fetch_assets  # noqa: E402
import gen_unicode  # noqa: E402
import unicode_profiles  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GEN = os.path.join(ROOT, "src", "gen")
HERE = os.path.dirname(os.path.abspath(__file__))

# Latin + Latin-1, Latin Extended-A (European names), basic Cyrillic,
# general punctuation (quotes, dashes, ellipsis, bullet) and arrows.
COMMON = "0x20-0x7e,0xa0-0x17f,0x400-0x45f,0x2010-0x2027,0x2190-0x2195"
FONTS = [
    # symbol,        bdf,              ranges
    ("font_small",  "spleen-5x8.bdf",  "0x20-0x7e,0xa0-0xff"),
    ("font_medium", "spleen-6x12.bdf", COMMON),
    ("font_large",  "spleen-8x16.bdf", COMMON),
    # Large text only: ASCII + Latin-1 (Latin Extended-A would cost ~6.6 KB).
    ("font_xlarge", "spleen-12x24.bdf", "0x20-0x7e,0xa0-0xff,0x2010-0x2027"),
]
# Spleen's stems are two pixels wide at 8x16, so Noto's Bold matches it there;
# the other sizes match with Regular.
NOTO = {"font_small": "noto_sans_mono.ttf", "font_medium": "noto_sans_mono.ttf",
        "font_large": "noto_sans_mono_bold.ttf", "font_xlarge": "noto_sans_mono.ttf"}
SCRIPTS = ("gen_fonts.py", "gen_unicode.py", "unicode_profiles.py", "bdf2c.py", "assets.lock")


def spec():
    return os.environ.get("MC_UNICODE", "").strip()


def stamp_of(norm):
    """Everything the output depends on: the profile, the generator, the inputs."""
    h = hashlib.sha256(norm.encode())
    for n in SCRIPTS:
        h.update(open(os.path.join(HERE, n), "rb").read())
    for _, bdf, _ in FONTS:
        h.update(open(os.path.join(ROOT, "fonts", bdf), "rb").read())
    return h.hexdigest()


def generate(norm, groups):
    os.makedirs(GEN, exist_ok=True)
    layers = {}
    report = [f"Unicode profile: {norm}", ""]
    total = 0
    for sym, bdf, ranges in FONTS:
        src = os.path.join(ROOT, "fonts", bdf)
        out = os.path.join(GEN, f"{sym}.c")
        luni = os.path.join(GEN, f"{sym}_uni.c")
        names = groups[sym]
        nxt = ""
        if names:
            _, glyphs = bdf2c.parse(src)
            spleen = {cp for cp in glyphs if bdf2c.in_ranges(cp, bdf2c.parse_ranges(ranges))}
            st = gen_unicode.layer(fetch_assets.get(NOTO[sym]), src, unicode_profiles.ranges_for(names), spleen,
                                                 luni, f"{sym}_uni")
            nxt = f"{sym}_uni"
            layers[sym] = st
            total += st["bytes"]
            w, h = st["cell"]
            report.append(f"{sym:12s} {w}x{h}  {','.join(names)}")
            report.append(f"{'':12s} {st['glyphs']} glyphs in {st['runs']} runs, {st['bytes']} bytes"
                          f" (noto at {st['pixel_size']} px)")
            if st["missing"]:
                report.append(f"{'':12s} not in Noto Sans Mono: {len(st['missing'])} code points"
                              f" ({', '.join('U+%04X' % c for c in st['missing'][:8])}"
                              f"{', ...' if len(st['missing']) > 8 else ''})")
            if st["clipped"]:
                report.append(f"{'':12s} wider than the cell, clipped: {len(st['clipped'])}")
        elif os.path.exists(luni):
            os.remove(luni)
        bdf2c.main(src, out, sym, sym, "0", "0", "ui/gfx/font.h", "mc_font_t", ranges, nxt)
    report += ["", f"fallback layers total: {total} bytes of flash"]
    with open(os.path.join(GEN, "unicode_report.txt"), "w") as f:
        f.write("\n".join(report) + "\n")
    hdr = os.path.join(GEN, "fonts.h")
    with open(hdr + ".tmp", "w") as h:
        h.write("/* Generated by scripts/gen_fonts.py; do not edit. */\n#pragma once\n"
                '#include "ui/gfx/font.h"\n#ifdef __cplusplus\nextern "C" {\n#endif\n')
        for sym, _, _ in FONTS:
            h.write(f"extern const mc_font_t {sym};\n")
        h.write("#ifdef __cplusplus\n}\n#endif\n")
    os.replace(hdr + ".tmp", hdr)
    cfg = os.path.join(GEN, "unicode_cfg.h")
    with open(cfg + ".tmp", "w") as h:
        h.write("/* Generated by scripts/gen_fonts.py; do not edit. */\n#pragma once\n"
                f'#define MC_UNICODE_PROFILE "{norm}"\n'
                f"#define MC_UNICODE_LAYERS {1 if layers else 0}\n")
    os.replace(cfg + ".tmp", cfg)
    return report


def main():
    try:
        norm, groups = unicode_profiles.resolve(spec())
    except ValueError as e:
        sys.exit(f"gen_fonts: MC_UNICODE: {e}")
    stamp_file = os.path.join(GEN, ".fonts.stamp")
    want = stamp_of(norm)
    try:
        current = open(stamp_file).read().strip() == want
    except OSError:
        current = False
    if current and "--report" not in sys.argv:
        return
    report = generate(norm, groups)
    with open(stamp_file, "w") as f:
        f.write(want + "\n")
    if "--report" in sys.argv:
        print("\n".join(report))


if __name__ == "__main__":
    main()
